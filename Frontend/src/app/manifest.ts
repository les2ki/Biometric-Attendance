import type { MetadataRoute } from "next"; // manifest type
import { GRAPHITE, PAPER_LIGHT } from "@/lib/token-hex"; // manifests can't read CSS variables

export default function manifest(): MetadataRoute.Manifest { // /manifest.webmanifest → "Install app" in Chrome (WP9)
  return { // the Web App Manifest
    name: process.env.NEXT_PUBLIC_APP_NAME || "Biometric Attendance", // full name
    short_name: "Attendance", // under the home-screen icon (spec §12)
    description: "Lecturer and administrator dashboard for fingerprint attendance.", // store/install text
    start_url: "/", // root decides login vs dashboard
    display: "standalone", // own window, no browser chrome
    background_color: PAPER_LIGHT, // splash screen = --color-paper
    theme_color: GRAPHITE, // title bar = --color-graphite
    icons: [ // install icons
      { src: "/icon/192", sizes: "192x192", type: "image/png", purpose: "any" }, // generated by app/icon.tsx
      { src: "/icon/512", sizes: "512x512", type: "image/png", purpose: "any" }, // large icon
      { src: "/icon/512", sizes: "512x512", type: "image/png", purpose: "maskable" }, // full-bleed background, glyph in the safe zone
    ],
  };
}
